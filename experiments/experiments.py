def _build(node, out):
    i = len(out['feature'])
    for values in out.values():
        values.append(None)
    if node[0] == 'leaf':
        _, label, n = node
        out['left'][i] = out['right'][i] = -1
        out['feature'][i], out['threshold'][i] = -2, -2.
        majority, minority = 0.9 * n, 0.1 * n
        out['value'][i] = [majority, minority] if label == 'decline' \
            else [minority, majority]
        out['n'][i] = n
        return i
    _, column, threshold, left, right = node
    out['feature'][i] = EXAMPLE_COLUMNS.index(column)
    out['threshold'][i] = threshold
    out['left'][i] = _build(left, out)
    out['right'][i] = _build(right, out)
    out['value'][i] = list(np.add(out['value'][out['left'][i]],
                                  out['value'][out['right'][i]]))
    out['n'][i] = out['n'][out['left'][i]] + out['n'][out['right'][i]]
    return i


def example_explainer():
    """The explainer of the toy example tree."""
    out = {k: [] for k in ('left', 'right', 'feature', 'threshold', 'value',
                           'n')}
    _build(EXAMPLE_TREE, out)
    tree = TreeStructure(out['left'], out['right'], out['feature'],
                         out['threshold'], out['value'], CLASSES,
                         feature_names=EXAMPLE_COLUMNS,
                         n_node_samples=out['n'])
    spec = FeatureSpec.from_column_names(
        EXAMPLE_COLUMNS, numerical=['income', 'age'],
        features=[Feature('income', 'numerical', integer=True),
                  Feature('age', 'numerical', integer=True)])
    return TreeCounterfactualExplainer(tree, spec)


def _cell(value):
    return '$-1$' if value == -1 else '${}$'.format(int(value))


def _header(m):
    if m.kind != 'numerical':
        return {'student': 'stu.', 'employed': 'emp.',
                'self-employed': 'self'}[m.category]
    lower = None if m.lower is None else int(float(m.lower) + 0.5)
    upper = None if m.upper is None else int(float(m.upper) - 0.5)
    if lower is None:
        return '$\\le {}$'.format(upper)
    if upper is None:
        return '$\\ge {}$'.format(lower)
    return '${}$--${}$'.format(lower, upper)


def toy_example(output=RESULTS):
    """Writes the toy example's tables and explanations."""
    os.makedirs(output, exist_ok=True)
    e = example_explainer()
    lmf = e.leaf_meta_features
    names = {int(leaf): '$\\ell_{}$'.format(i + 1)
             for i, leaf in enumerate(lmf.leaf_ids)}
    alice = e.spec.encode(ALICE)
    x = mf.instance_meta_features(alice, e.meta_features)
    groups = sorted(lmf.groups, key=lambda g: min(g[2]))
    spans, start = [], 3
    for _, _, indices in groups:
        spans.append((start, start + len(indices) - 1))
        start += len(indices)
    distances = e.explain_instance(alice).leaf_distances.tolist()
    meta = ['\\begin{tabular}{ll' + 'c' * len(e.meta_features) + 'c}',
            '\\toprule',
            ' & & ' + ' & '.join('\\multicolumn{{{}}}{{c}}{{{}}}'.format(
                len(indices), name) for _, name, indices in groups)
            + ' & \\\\',
            ''.join('\\cmidrule(lr){{{}-{}}}'.format(a, b)
                    for a, b in spans),
            'leaf & class & '
            + ' & '.join(_header(m) for m in e.meta_features)
            + ' & $d(x, \\ell)$ \\\\', '\\midrule']
    for leaf, label, row, d in zip(lmf.leaf_ids, lmf.leaf_classes,
                                   lmf.matrix, distances):
        meta.append('{} & {} & {} & ${}$ \\\\'.format(
            names[int(leaf)], label, ' & '.join(_cell(v) for v in row), d))
    meta += ['\\midrule', '$x$ & decline & ' + ' & '.join(
        _cell(v) for v in x) + ' & \\\\', '\\bottomrule', '\\end{tabular}']
    # the leaf-to-leaf differences, with the pairs of leaves of different
    # classes -- those that raise the volatility index -- shaded (requires
    # the colortbl and xcolor packages)
    matrix, ids, classes = e.leaf_distance_matrix()
    # leaves grouped by class, so the shaded cells form blocks
    order = sorted(range(len(ids)), key=lambda i: (
        list(dict.fromkeys(classes)).index(classes[i]), i))
    matrix, ids, classes = matrix[np.ix_(order, order)], ids[order], \
        classes[order]
    table = ['\\begin{tabular}{ll' + 'c' * len(ids) + 'c}', '\\toprule',
             'leaf & class & ' + ' & '.join(names[int(i)] for i in ids)
             + ' & $\\nu$ \\\\', '\\midrule']
    for leaf, label, row in zip(ids, classes, matrix):
        cells = [('\\cellcolor{black!15}' if other != label else '') + str(v)
                 for v, other in zip(row, classes)]
        table.append('{} & {} & {} & ${:.2f}$ \\\\'.format(
            names[int(leaf)], label, ' & '.join(cells),
            e.volatility_index(int(leaf))))
    table += ['\\bottomrule', '\\end{tabular}']
    with open(os.path.join(output, 'toy_example_tables.tex'), 'w') as f:
        f.write('% generated by experiments/experiments.py -- do not edit\n')
        f.write('\\newcommand{\\metafeaturetable}{%\n' + '\n'.join(meta)
                + '}\n')
        f.write('\\newcommand{\\leafdistancetable}{%\n' + '\n'.join(table)
                + '}\n')
    lines = []
    for label, point in (('Alice', ALICE), ('Bob', BOB)):
        x = e.spec.encode(point)
        explanation = e.explain_instance(x)
        lines.append('== {} {} -> {} {}'.format(
            label, point, names[explanation.leaf], explanation.prediction))
        lines += e.explanation_text(explanation, integer_ranges=True)
        lines.append('-- supportive')
        lines += e.supportive_text(x, integer_ranges=True)
        lines.append('-- invariance ranges')
        for f, v in e.describe({0: e.invariance_ranges(x)},
                               integer_ranges=True)[0].items():
            lines.append('{}: {}'.format(f, v['wannabe']))
        lines.append('-- contextualised')
        lines += e.explanation_text(explanation, e.contextualise(explanation),
                                    integer_ranges=True)[1:]
        lines.append('')
    with open(os.path.join(output, 'toy_example.txt'), 'w') as f:
        f.write('\n'.join(lines))
    return '\n'.join(lines)


