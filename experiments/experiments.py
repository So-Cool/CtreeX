"""
Runs CtreeX algorithm experiments.

* A toy example implementing a small loan tree whose meta-feature table and
  leaf-to-leaf differences are written as LaTeX tables, with all its
  explanations in words.
* A comparison of CtreeX's counterfactual regions with the closest
  counterfactual point generated by a reimplementation of the tree-specific
  counterfactual explainer (its variant for axis-aligned trees) proposed by
  Carreira-Perpinan and Hada (AAAI, 2021) as well as an analysis of the
  explanation compression rate.
* A comparison of CtreeX with the formal contrastive and abductive
  explanations implemented by PyXAI (classification trees only).

The data sets used for the experiments are German Credit, Adult,
FICO HELOC and California Housing.
They are downloaded on first use into ``data/``;
the first two come from the UCI repository, FICO HELOC comes from the
fico-challenge package and California Housing is pulled by scikit-learn.

Every data set gets trees of depth 4, 6, 8 and 12;
``experiments.ipynb`` runs the code and shows the results, which are recorded
in the ``results.`` directory (CSV files and LaTeX tables).

Usage (Python 3.11 or newer)::

    uv sync --group experiments --group notebooks
    uv run python experiments.py                   # everything
    uv run python experiments.py --quick           # a smoke test
    uv run jupyter lab ./                          # the notebook

The XGBoost package -- which is a dependency of PyXAI -- requires OpenMP
runtime;
run ``brew install libomp`` on MacOS to install it.
"""
