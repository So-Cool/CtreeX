@dataclasses.dataclass
class Dataset:
    """A one-hot encoded dataset with its feature specification."""
    name: str
    task: str  # 'classification' or 'regression'
    X: np.ndarray
    y: np.ndarray
    spec: FeatureSpec


def _download(url, name):
    os.makedirs(DATA, exist_ok=True)
    path = os.path.join(DATA, name)
    if not os.path.exists(path):
        urllib.request.urlretrieve(url, path)
    return path


def _encode(name, task, frame, target, numerical):
    """One-hot encodes the categorical columns of a data frame."""
    columns = []
    for column in frame.columns:
        if column in numerical:
            columns.append((column, None))
        else:
            columns += [(column, str(c))
                        for c in sorted(frame[column].astype(str).unique())]
    features = [Feature(c, 'numerical' if c in numerical else 'categorical')
                for c in frame.columns]
    spec = FeatureSpec(columns, features=features, separator=SEPARATOR)
    X = np.column_stack([
        frame[f].to_numpy(dtype=float) if c is None
        else (frame[f].astype(str) == c).to_numpy(dtype=float)
        for f, c in columns])
    return Dataset(name, task, X, np.asarray(target), spec)


