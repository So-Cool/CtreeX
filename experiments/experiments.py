# ------------------------------------------------------------ the baseline
class ClosestPoint:
    """
    The exact closest counterfactual point of an axis-aligned tree
    (Carreira-Perpinan and Hada, AAAI 2021):
    the data point is projected onto the box of every target leaf and
    the closest projection is kept.
    Numerical features cost the L1 distance scaled by their range in the
    training data, a changed categorical feature costs 1.
    """

    def __init__(self, tree, spec, X_train):
        self.tree, self.spec = tree, spec
        self.numerical = [j for j, (_, c) in enumerate(spec.columns)
                          if c is None]
        self.categorical = [j for j, (_, c) in enumerate(spec.columns)
                            if c is not None]
        ranges = np.ptp(X_train[:, self.numerical], axis=0)
        self.ranges = np.where(ranges > 0, ranges, 1.)
        paths = mf.tree_paths(tree, spec)
        self.leaves = np.array([p.leaf for p in paths])
        n = len(paths)
        self.low = np.full((n, len(self.numerical)), -np.inf)
        self.high = np.full((n, len(self.numerical)), np.inf)
        # whether each one-hot column (category) is allowed in each leaf
        self.allowed = np.ones((n, len(self.categorical)), dtype=bool)
        position = {j: k for k, j in enumerate(self.numerical)}
        category = {j: k for k, j in enumerate(self.categorical)}
        for i, path in enumerate(paths):
            for name, operator, value in path.conditions:
                j = spec.column_index(name)
                if j in position:
                    k = position[j]
                    if operator == '<=':
                        self.high[i, k] = min(self.high[i, k], value)
                    else:
                        self.low[i, k] = max(self.low[i, k], value)
                elif value == 1:  # this category only
                    feature = spec.columns[j][0]
                    for other in self.categorical:
                        if spec.columns[other][0] == feature and other != j:
                            self.allowed[i, category[other]] = False
                else:  # not this category
                    self.allowed[i, category[j]] = False
        self.feature_of = np.array([spec.columns[j][0]
                                    for j in self.categorical])
        self.features = list(dict.fromkeys(self.feature_of))
        # the smallest 32-bit number above every lower bound and the largest
        # one at most every upper bound (scikit-learn compares 32-bit data)
        low32 = self.low.astype(np.float32)
        self.above = np.where(low32.astype(float) <= self.low,
                              np.nextafter(low32, np.float32(np.inf)),
                              low32).astype(float)
        high32 = self.high.astype(np.float32)
        self.at_most = np.where(high32.astype(float) > self.high,
                                np.nextafter(high32, np.float32(-np.inf)),
                                high32).astype(float)

    def explain(self, x, target_leaves):
        """The closest point in the target leaves and the number of features
        it changes."""
        rows = np.flatnonzero(np.isin(self.leaves, target_leaves))
        values = x[self.numerical]
        below = values <= self.low[rows]
        over = values > self.high[rows]
        moved = np.where(below, self.above[rows],
                         np.where(over, self.at_most[rows], values))
        cost = (np.abs(moved - values) / self.ranges).sum(axis=1)
        own = x[self.categorical] == 1
        # a categorical feature changes when its category is not allowed
        changed = {}
        for feature in self.features:
            columns = self.feature_of == feature
            ok = (self.allowed[rows][:, columns] & own[columns]).any(axis=1)
            changed[feature] = ~ok
            cost = cost + changed[feature]
        best = int(np.argmin(cost))
        point = x.astype(float).copy()
        point[self.numerical] = moved[best]
        n_changed = int((moved[best] != values).sum())
        for feature in self.features:
            if changed[feature][best]:
                columns = np.flatnonzero(self.feature_of == feature)
                allowed = columns[self.allowed[rows[best], columns]]
                point[np.array(self.categorical)[columns]] = 0.
                point[self.categorical[allowed[0]]] = 1.
                n_changed += 1
        leaf = int(self.tree.apply(point.reshape(1, -1))[0])
        if leaf != self.leaves[rows[best]]:  # pragma: no cover
            raise RuntimeError('The closest point misses its leaf.')
        return point, n_changed


# ------------------------------------------------------------- experiments
def _targets(task):
    if task == 'classification':
        return [('other class', OtherClass())]
    return [('+$50k', ValueChange(+REGRESSION_CHANGE)),
            ('-$50k', ValueChange(-REGRESSION_CHANGE))]


def _sample(n, rng):
    return np.sort(rng.choice(n, size=min(POINTS, n), replace=False))


def train(dataset, depth, X_train, y_train):
    model = DecisionTreeClassifier if dataset.task == 'classification' \
        else DecisionTreeRegressor
    return model(max_depth=depth, min_samples_leaf=MIN_SAMPLES_LEAF,
                 random_state=SEED).fit(X_train, y_train)


def point_vs_ctreex(dataset, depth, tree, X_train, points):
    """Closest point versus CtreeX's regions, for every point and target."""
    explainer = TreeCounterfactualExplainer(tree, dataset.spec)
    baseline = ClosestPoint(explainer.tree, dataset.spec, X_train)
    rows = []
    for i, x in enumerate(points):
        leaf = explainer.predict_leaf(x)
        for name, target in _targets(dataset.task):
            mask = tgt.select_targets(target, explainer.target_context(leaf))
            leaves = explainer.leaf_meta_features.leaf_ids[mask]
            if not leaves.size:
                continue  # no leaf reaches the target
            start = time.perf_counter()
            explanation = explainer.explain_instance(x, target=target)
            ctreex_time = time.perf_counter() - start
            found = [c for c in explanation.counterfactuals if c.per_leaf]
            if not found:  # target leaves only beyond max_distance
                continue
            start = time.perf_counter()
            _, n_changed = baseline.explain(x, leaves)
            baseline_time = time.perf_counter() - start
            smallest = found[0]
            rows.append({
                'dataset': dataset.name, 'depth': depth, 'point': i,
                'target': name, 'ctreex_distance': smallest.distance,
                'point_changed': n_changed,
                'target_leaves': len(smallest.per_leaf),
                'ranked': len(smallest.ranked),
                'compression': len(smallest.per_leaf) / len(smallest.ranked),
                'ctreex_ms': 1000 * ctreex_time,
                'point_ms': 1000 * baseline_time})
    return rows


def _import_pyxai():
    """PyXAI parses the command line when imported so hide it."""
    arguments, sys.argv = sys.argv, sys.argv[:1]
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            from pyxai import Explaining, Learning
    finally:
        sys.argv = arguments
    return Explaining, Learning


def _pyxai(tree, dataset, X_train, y_train):
    Explaining, Learning = _import_pyxai()
    frame = pd.DataFrame(X_train, columns=dataset.spec.column_names)
    frame['target'] = y_train
    with contextlib.redirect_stdout(io.StringIO()):
        _, model = Learning.ModelIO.import_models(
            tree, frame, problem_type='classification',
            instances_type='tabular', labels_type='classes')
        explainer = Explaining.initialize(model, X_train[0])
    return explainer


def _features(spec, details):
    """The base features of PyXAI's (one-hot) columns."""
    return frozenset(spec.columns[spec.column_index(name)][0]
                     for name in details)


def pyxai_vs_ctreex(dataset, depth, tree, X_train, y_train, points):
    """CtreeX versus PyXAI's contrastive and abductive explanations."""
    Explaining, _ = _import_pyxai()
    explainer = TreeCounterfactualExplainer(tree, dataset.spec)
    pyxai = _pyxai(tree, dataset, X_train, y_train)
    rows = []
    for i, x in enumerate(points):
        start = time.perf_counter()
        explanation = explainer.explain_instance(x)
        supportive = explainer.supportive_explanations(x)
        ctreex_time = time.perf_counter() - start
        found = [c for c in explanation.counterfactuals if c.per_leaf]
        ctreex_sets = {frozenset(changes)
                       for changes in found[0].per_leaf.values()}
        with contextlib.redirect_stdout(io.StringIO()):
            start = time.perf_counter()
            pyxai.set_instance(x)
            reasons = pyxai.contrastive_reason(n=Explaining.ALL)
            sufficient = pyxai.minimal_sufficient_reason(
                n=1, time_limit=PYXAI_TIME_LIMIT)
            pyxai_time = time.perf_counter() - start
        reasons = [r for r in reasons if r]
        sets = [_features(dataset.spec, pyxai.to_features(
            r, details=True, contrastive=True)) for r in reasons]
        smallest = min(len(s) for s in sets)
        pyxai_sets = {s for s in sets if len(s) == smallest}
        fewest = min(len(r) for r in reasons)
        by_conditions = min(len(s) for s, r in zip(sets, reasons)
                            if len(r) == fewest)
        timeout = sufficient is None or len(sufficient) == 0
        axp = None if timeout else len(_features(
            dataset.spec, pyxai.to_features(sufficient, details=True)))
        rows.append({
            'dataset': dataset.name, 'depth': depth, 'point': i,
            'cxp_agree': ctreex_sets == pyxai_sets,
            'conditions_miss': by_conditions > smallest,
            'pyxai_axp': axp,
            'ctreex_supportive': len(supportive[0].conditions),
            'pyxai_timeout': timeout,
            'pyxai_ms': 1000 * pyxai_time, 'ctreex_ms': 1000 * ctreex_time})
    return rows


def run(datasets=tuple(DATASETS), depths=DEPTHS, output=RESULTS,
        verbose=True):
    """Runs both experiments and saves the results (CSV files) and tables."""
    os.makedirs(output, exist_ok=True)
    models, first, second = [], [], []
    for key in datasets:
        dataset = DATASETS[key]()
        stratify = dataset.y if dataset.task == 'classification' else None
        X_train, X_test, y_train, y_test = train_test_split(
            dataset.X, dataset.y, test_size=0.2, random_state=SEED,
            stratify=stratify)
        points = X_test[_sample(len(X_test), np.random.default_rng(SEED))]
        for depth in depths:
            tree = train(dataset, depth, X_train, y_train)
            predictions = tree.predict(X_test)
            score = (balanced_accuracy_score(y_test, predictions)
                     if dataset.task == 'classification'
                     else r2_score(y_test, predictions))
            models.append({'dataset': dataset.name, 'depth': depth,
                           'tree_depth': tree.get_depth(),
                           'leaves': tree.get_n_leaves(),
                           'score': score, 'points': len(points)})
            first += point_vs_ctreex(dataset, depth, tree, X_train, points)
            if dataset.task == 'classification':
                second += pyxai_vs_ctreex(dataset, depth, tree, X_train,
                                          y_train, points)
            if verbose:
                print('{} depth {}: {} leaves, score {:.3f}'.format(
                    dataset.name, depth, tree.get_n_leaves(), score))
    frames = {'models': pd.DataFrame(models),
              'point_vs_ctreex': pd.DataFrame(first),
              'pyxai_vs_ctreex': pd.DataFrame(second)}
    for name, frame in frames.items():
        frame.to_csv(os.path.join(output, name + '.csv'), index=False)
    write_tables(frames, output, depth=REPORTED_DEPTH
                 if REPORTED_DEPTH in depths else max(depths))
    return frames


# ------------------------------------------------------------------ tables
def _spread(grouped, column, prefix=None):
    """Mean and standard deviation (counts and sizes) of a column."""
    prefix = prefix or column
    return {prefix + '_mean': grouped[column].mean(),
            prefix + '_sd': grouped[column].std()}


def _quartiles(grouped, column):
    """Median and interquartile range (run times, which are skewed)."""
    return {column + '_median': grouped[column].median(),
            column + '_q1': grouped[column].quantile(0.25),
            column + '_q3': grouped[column].quantile(0.75)}


def summarise_point_vs_ctreex(point_vs_ctreex_frame):
    """Per dataset and depth: means and standard deviations of the counts,
    the share of points whose closest point is not the sparsest and medians;
    interquartile ranges of the times."""
    grouped = point_vs_ctreex_frame.groupby(['dataset', 'depth'], sort=False)
    return pd.DataFrame({
        **_spread(grouped, 'point_changed'),
        **_spread(grouped, 'ctreex_distance'),
        'not_sparsest': grouped.apply(
            lambda g: 100 * (g['point_changed'] > g['ctreex_distance'])
            .mean(), include_groups=False),
        **_spread(grouped, 'compression'),
        **_quartiles(grouped, 'point_ms'),
        **_quartiles(grouped, 'ctreex_ms'),
        'explanations': grouped.size()}).reset_index()


def summarise_pyxai_vs_ctreex(pyxai_vs_ctreex_frame):
    """Per dataset and depth: the agreement shares, means and standard
    deviations of the explanation sizes;
    medians and interquartile ranges of the times."""
    grouped = pyxai_vs_ctreex_frame.groupby(['dataset', 'depth'], sort=False)
    return pd.DataFrame({
        'cxp_agree': 100 * grouped['cxp_agree'].mean(),
        'conditions_miss': 100 * grouped['conditions_miss'].mean(),
        **_spread(grouped, 'pyxai_axp'),
        **_spread(grouped, 'ctreex_supportive'),
        **_quartiles(grouped, 'pyxai_ms'),
        **_quartiles(grouped, 'ctreex_ms'),
        'timeouts': grouped['pyxai_timeout'].sum(),
        'points': grouped.size()}).reset_index()


def _number(value, digits=1):
    if isinstance(value, (int, np.integer)):
        return str(value)
    return '{:.{}f}'.format(value, digits)


def _mean_sd(row, prefix):
    mean = _number(row[prefix + '_mean'], 2)
    sd = _number(row[prefix + '_sd'], 2)
    return '${} \\pm {}$'.format(mean, sd)


def _median_iqr(row, prefix):
    return '{} ({}--{})'.format(_number(row[prefix + '_median'], 2),
                                _number(row[prefix + '_q1'], 2),
                                _number(row[prefix + '_q3'], 2))


def write_tables(frames, output, depth=REPORTED_DEPTH):
    """
    LaTeX tables with experimental results (the depth-``depth`` trees):
    counts and sizes as mean $\\pm$ standard deviation, shares in percent and
    times as median (interquartile range).
    """
    one = summarise_point_vs_ctreex(frames['point_vs_ctreex'])
    one = one[one['depth'] == depth]
    lines = ['% generated by experiments/experiments.py -- do not edit',
             '% counts: mean $\\pm$ SD; times: median (IQR)',
             '\\begin{tabular}{lrrrrrr}', '\\toprule',
             ' & \\multicolumn{2}{c}{features changed} & not sparsest '
             '& compression & \\multicolumn{2}{c}{time (ms)} \\\\',
             '\\cmidrule(lr){2-3}\\cmidrule(lr){6-7}',
             'dataset & point & CtreeX & (\\%) & (leaves / CF) & point '
             '& CtreeX \\\\', '\\midrule']
    for _, row in one.iterrows():
        lines.append('{} & {} & {} & {} & {} & {} & {} \\\\'.format(
            row['dataset'], _mean_sd(row, 'point_changed'),
            _mean_sd(row, 'ctreex_distance'), _number(row['not_sparsest']),
            _mean_sd(row, 'compression'), _median_iqr(row, 'point_ms'),
            _median_iqr(row, 'ctreex_ms')))
    lines += ['\\bottomrule', '\\end{tabular}']
    with open(os.path.join(output, 'point_vs_ctreex.tex'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    if frames['pyxai_vs_ctreex'].empty:
        return
    two = summarise_pyxai_vs_ctreex(frames['pyxai_vs_ctreex'])
    two = two[two['depth'] == depth]
    lines = ['% generated by experiments/experiments.py -- do not edit',
             '% sizes: mean $\\pm$ SD; times: median (IQR)',
             '\\begin{tabular}{lrrrrrr}', '\\toprule',
             ' & CXp agree & fewest conditions & \\multicolumn{2}{c}{AXp '
             'size} & \\multicolumn{2}{c}{time (ms)} \\\\',
             '\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}',
             'dataset & (\\%) & $\\ne$ fewest features (\\%) & PyXAI '
             '& CtreeX & PyXAI & CtreeX \\\\', '\\midrule']
    for _, row in two.iterrows():
        lines.append('{} & {} & {} & {} & {} & {} & {} \\\\'.format(
            row['dataset'], _number(row['cxp_agree']),
            _number(row['conditions_miss']), _mean_sd(row, 'pyxai_axp'),
            _mean_sd(row, 'ctreex_supportive'),
            _median_iqr(row, 'pyxai_ms'), _median_iqr(row, 'ctreex_ms')))
    lines += ['\\bottomrule', '\\end{tabular}']
    with open(os.path.join(output, 'pyxai_vs_ctreex.tex'), 'w') as f:
        f.write('\n'.join(lines) + '\n')


